-- Start clean (only touches Artifax tables)
DROP TABLE IF EXISTS "OrderHistories"        CASCADE;
DROP TABLE IF EXISTS "Orders"                CASCADE;
DROP TABLE IF EXISTS "BranchItemCapacities"  CASCADE;
DROP TABLE IF EXISTS "ItemIngredients"       CASCADE;
DROP TABLE IF EXISTS "Employees"             CASCADE;
DROP TABLE IF EXISTS "Items"                 CASCADE;
DROP TABLE IF EXISTS "Branches"              CASCADE;
DROP TABLE IF EXISTS "OrderItems"            CASCADE;  -- old unused table

-- ---------------------------------------------------------------------
--  TABLES  (names/columns match the EF Core models exactly — quoted
--  PascalCase is required because that is what the .NET backend queries)
-- ---------------------------------------------------------------------

CREATE TABLE "Branches" (
    "BranchID"   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BranchName" text NOT NULL
);

CREATE TABLE "Items" (
    "ItemID"         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ItemName"       text,
    "ItemCategory"   text,          -- metal | mechanical | electronics | furniture | other
    "ProductionTime" integer NOT NULL,  -- minutes per unit (0 = base material)
    "Price"          real
);

CREATE TABLE "Employees" (
    "EmployeeId"           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "EmployeeEmail"        text,
    "EmployeeName"         text,
    "EmployeePasswordHash" text,     -- used by the current login; removed when we switch to Supabase Auth
    "BranchId"             integer NOT NULL REFERENCES "Branches"("BranchID") ON DELETE CASCADE,
    "EmployeeLevel"        text,     -- 'Admin' or 'Employee'
    "TwoFactorSecret"      text,     -- used by the current 2FA; removed when we switch to Supabase MFA
    "AuthUserId"           uuid UNIQUE REFERENCES auth.users(id) ON DELETE SET NULL  -- link to Supabase Auth (filled in later)
);
CREATE UNIQUE INDEX "IX_Employees_EmployeeEmail" ON "Employees" ("EmployeeEmail");
CREATE INDEX "IX_Employees_BranchId" ON "Employees" ("BranchId");

-- Blueprints: ProductID is made from IngredientQuantity x IngredientID
CREATE TABLE "ItemIngredients" (
    "ItemIngredientID"   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ProductID"          integer NOT NULL REFERENCES "Items"("ItemID") ON DELETE CASCADE,
    "IngredientID"       integer NOT NULL REFERENCES "Items"("ItemID") ON DELETE CASCADE,
    "IngredientQuantity" integer NOT NULL
);
CREATE INDEX "IX_ItemIngredients_ProductID"    ON "ItemIngredients" ("ProductID");
CREATE INDEX "IX_ItemIngredients_IngredientID" ON "ItemIngredients" ("IngredientID");

-- Stock per branch
CREATE TABLE "BranchItemCapacities" (
    "BranchItemCapacityID" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BranchID"     integer NOT NULL REFERENCES "Branches"("BranchID") ON DELETE CASCADE,
    "ItemID"       integer NOT NULL REFERENCES "Items"("ItemID") ON DELETE CASCADE,
    "ItemQuantity" integer NOT NULL
);
CREATE INDEX "IX_BranchItemCapacities_BranchID" ON "BranchItemCapacities" ("BranchID");
CREATE INDEX "IX_BranchItemCapacities_ItemID"   ON "BranchItemCapacities" ("ItemID");

-- Crafting jobs
CREATE TABLE "Orders" (
    "OrderID"           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ItemID"            integer NOT NULL REFERENCES "Items"("ItemID") ON DELETE CASCADE,
    "Quantity"          integer NOT NULL,
    "CreatedDateTime"   timestamptz NOT NULL DEFAULT now(),
    "StartedDateTime"   timestamptz,
    "CompletedDateTime" timestamptz,
    "TotalTime"         integer NOT NULL DEFAULT 0,   -- minutes
    "TimeElapsed"       integer NOT NULL DEFAULT 0,   -- minutes
    "BranchID"          integer NOT NULL REFERENCES "Branches"("BranchID") ON DELETE CASCADE,
    "EmployeeID"        integer NOT NULL REFERENCES "Employees"("EmployeeId") ON DELETE CASCADE,
    "OrderExpedite"     boolean NOT NULL DEFAULT false,
    "Status"            text    NOT NULL DEFAULT 'Queued'  -- Queued | Active | Paused | Cancelled | Complete
);
CREATE INDEX "IX_Orders_ItemID"     ON "Orders" ("ItemID");
CREATE INDEX "IX_Orders_BranchID"   ON "Orders" ("BranchID");
CREATE INDEX "IX_Orders_EmployeeID" ON "Orders" ("EmployeeID");
CREATE INDEX "IX_Orders_Status"     ON "Orders" ("Status");

CREATE TABLE "OrderHistories" (
    "OrderHistoryID"      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "OrderID"             integer NOT NULL REFERENCES "Orders"("OrderID") ON DELETE CASCADE,
    "PreviousStatus"      text NOT NULL DEFAULT '',
    "NewStatus"           text NOT NULL DEFAULT '',
    "ChangedDateTime"     timestamptz NOT NULL DEFAULT now(),
    "ChangedByEmployeeID" integer REFERENCES "Employees"("EmployeeId") ON DELETE SET NULL,
    "ChangeReason"        text
);
CREATE INDEX "IX_OrderHistories_OrderID"             ON "OrderHistories" ("OrderID");
CREATE INDEX "IX_OrderHistories_ChangedByEmployeeID" ON "OrderHistories" ("ChangedByEmployeeID");

-- ---------------------------------------------------------------------
--  SECURITY: lock the tables away from Supabase's public Data API.
--  The backend connects as the database owner, which bypasses RLS,
--  so the app keeps working — but nobody can read the tables directly
--  with the public anon key.
-- ---------------------------------------------------------------------
ALTER TABLE "Branches"             ENABLE ROW LEVEL SECURITY;
ALTER TABLE "Items"                ENABLE ROW LEVEL SECURITY;
ALTER TABLE "Employees"            ENABLE ROW LEVEL SECURITY;
ALTER TABLE "ItemIngredients"      ENABLE ROW LEVEL SECURITY;
ALTER TABLE "BranchItemCapacities" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "Orders"               ENABLE ROW LEVEL SECURITY;
ALTER TABLE "OrderHistories"       ENABLE ROW LEVEL SECURITY;

